// Markers that must never appear in plaintext on the remote.
var secrets = []string{
	"SECRET_CONTENT_7f3a", "secret_module_name", "SECRET_MSG_91c2",
	"AliceSecretAuthor", "alice-secret@example.com", "secret-branch-x", "v-secret-tag",
	"BOB_SECRET_LINE", "alice@example.com",
}

type env struct {
	t      *testing.T
	root   string
	bin    string
	remote string
}

type user struct {
	e    *env
	name string
	home string
	vars []string
}

func moduleRoot(t *testing.T) string {
	out, err := exec.Command("go", "env", "GOMOD").Output()
	if err != nil {
		t.Fatal(err)
	}
	return filepath.Dir(strings.TrimSpace(string(out)))
}

func newEnv(t *testing.T) *env {
	if testing.Short() {
		t.Skip("e2e")
	}
	root := t.TempDir()
	e := &env{t: t, root: root, bin: filepath.Join(root, "bin"), remote: filepath.Join(root, "remote.git")}
	exe := ""
	if runtime.GOOS == "windows" {
		exe = ".exe"
	}
	args := []string{"build", "-o", filepath.Join(e.bin, "genc"+exe)}
	if d := os.Getenv("GENC_COVERDIR"); d != "" {
		// collect coverage from the real binaries (go build -cover + GOCOVERDIR)
		args = append(args, "-cover", "-coverpkg=genc/...")
		os.Setenv("GOCOVERDIR", d)
	}
	build := exec.Command("go", append(args, ".")...)
	build.Dir = moduleRoot(t)
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build: %v\n%s", err, out)
	}
	b, _ := os.ReadFile(filepath.Join(e.bin, "genc"+exe))
	os.WriteFile(filepath.Join(e.bin, "git-remote-genc"+exe), b, 0o755)
	gitcfg := filepath.Join(root, "gitconfig")
	os.WriteFile(gitcfg, []byte("[init]\n\tdefaultBranch = main\n[advice]\n\tdetachedHead = false\n"), 0o644)
	t.Setenv("GIT_CONFIG_GLOBAL", gitcfg)
	t.Setenv("GIT_CONFIG_NOSYSTEM", "1")
	t.Setenv("PATH", e.bin+string(os.PathListSeparator)+os.Getenv("PATH"))
	e.git(root, "init", "-q", "--bare", e.remote)
	return e
}

func (e *env) newUser(name string) *user {
	home := filepath.Join(e.root, "home-"+name)
	os.MkdirAll(home, 0o700)
	return &user{e: e, name: name, home: home, vars: []string{
		"GENC_HOME=" + filepath.Join(home, "genc"),
		"GENC_IDENTITY=" + filepath.Join(home, "genc", "id_ed25519"),
		"HOME=" + home, "USERPROFILE=" + home,
		"GIT_AUTHOR_NAME=" + name, "GIT_AUTHOR_EMAIL=" + name + "@example.com",
		"GIT_COMMITTER_NAME=" + name, "GIT_COMMITTER_EMAIL=" + name + "@example.com",
	}}
}

// user creates a user with a fresh, unprotected key generated by genc keygen.
func (e *env) user(name string) *user {
	u := e.newUser(name)
	u.ok(u.home, "genc", "keygen")
	return u
}

func (u *user) keyPath() string { return filepath.Join(u.home, "genc", "id_ed25519") }
func (u *user) pub() string     { return u.keyPath() + ".pub" }

func (u *user) pubLine() string {
	b, err := os.ReadFile(u.pub())
	if err != nil {
		u.e.t.Fatal(err)
	}
	return strings.TrimSpace(string(b))
}

func (e *env) git(dir string, args ...string) string {
	e.t.Helper()
	c := exec.Command("git", args...)
	c.Dir = dir
	out, err := c.CombinedOutput()
	if err != nil {
		e.t.Fatalf("git %v: %v\n%s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func (u *user) cmd(dir string, args ...string) *exec.Cmd {
	c := exec.Command(args[0], args[1:]...)
	c.Dir = dir
	c.Env = append(os.Environ(), u.vars...)
	return c
}

func (u *user) run(dir string, args ...string) (string, error) {
	out, err := u.cmd(dir, args...).CombinedOutput()
	return strings.TrimSpace(string(out)), err
}

func (u *user) ok(dir string, args ...string) string {
	u.e.t.Helper()
	out, err := u.run(dir, args...)
	if err != nil {
		u.e.t.Fatalf("[%s] %v failed: %v\n%s", u.name, args, err, out)
	}
	return out
}

func (u *user) fail(dir string, want string, args ...string) string {
	u.e.t.Helper()
	out, err := u.run(dir, args...)
	if err == nil {
		u.e.t.Fatalf("[%s] %v unexpectedly succeeded\n%s", u.name, args, out)
	}
	if want != "" && !strings.Contains(out, want) {
		u.e.t.Fatalf("[%s] %v: expected %q in output:\n%s", u.name, args, want, out)
	}
	return out
}

func write(t *testing.T, path, content string) {
	os.MkdirAll(filepath.Dir(path), 0o755)
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// writeProtectedKey creates an ed25519 key pair protected by a passphrase.
func writeProtectedKey(t *testing.T, path, pass string) {
	_, priv, _ := genEd25519()
	block, err := ssh.MarshalPrivateKeyWithPassphrase(priv, "", []byte(pass))
	if err != nil {
		t.Fatal(err)
	}
	os.MkdirAll(filepath.Dir(path), 0o700)
	os.WriteFile(path, pemBytes(block), 0o600)
	sp, _ := ssh.NewPublicKey(priv.Public())
	os.WriteFile(path+".pub", ssh.MarshalAuthorizedKey(sp), 0o644)
}

// ---- remote inspection ----

// assertNoLeak scans every object in the remote (reachable or not), all ref names
// and the storage commit metadata.
func (e *env) assertNoLeak(stage string) {
	e.t.Helper()
	out, err := exec.Command("git", "--git-dir="+e.remote, "cat-file", "--batch-all-objects", "--batch", "--unordered").Output()
	if err != nil {
		e.t.Fatal(err)
	}
	for _, s := range secrets {
		if bytes.Contains(out, []byte(s)) {
			e.t.Fatalf("[%s] LEAK: %q found in remote objects", stage, s)
		}
	}
	if refs := e.git(e.root, "--git-dir="+e.remote, "for-each-ref", "--format=%(refname)"); refs != "refs/heads/main" {
		e.t.Fatalf("[%s] remote has unexpected refs: %q", stage, refs)
	}
	authors := e.git(e.root, "--git-dir="+e.remote, "log", "--format=%an <%ae> %cn <%ce> %s", "main")
	for _, l := range strings.Split(authors, "\n") {
		if l != "genc <genc@localhost> genc <genc@localhost> genc update" {
			e.t.Fatalf("[%s] remote commit metadata leaks: %q", stage, l)
		}
	}
}

func (e *env) blob(rev string) []byte {
	out, err := exec.Command("git", "--git-dir="+e.remote, "cat-file", "blob", rev).Output()
	if err != nil {
		e.t.Fatal(err)
	}
	return out
}

func (e *env) remoteHead() string { return e.git(e.root, "--git-dir="+e.remote, "rev-parse", "main") }

func (e *env) setRemoteHead(sha string) {
	e.git(e.root, "--git-dir="+e.remote, "update-ref", "refs/heads/main", sha)
}

// ---- attacker tooling: writes to the remote directly, like someone with push access ----

// manifest mirrors genc's public manifest format.
type manifest struct {
	Format  int      `json:"format"`
	RepoID  string   `json:"repo_id"`
	KeyID   string   `json:"key_id"`
	Version uint64   `json:"version"`
	Prev    string   `json:"prev"`
	Members []member `json:"members"`
	Signer  string   `json:"signer"`
	Time    string   `json:"time"`
}

type member struct {
	FP  string `json:"fp"`
	Key string `json:"key"`
}

func (e *env) readManifest(rev string) manifest {
	var m manifest
	if err := json.Unmarshal(e.blob(rev+":keys/manifest.json"), &m); err != nil {
		e.t.Fatal(err)
	}
	return m
}

func fingerprint(pub ssh.PublicKey) string {
	h := sha256.Sum256(pub.Marshal())
	return hex.EncodeToString(h[:8])
}

func (e *env) readTree(commit string) map[string]string {
	out, err := exec.Command("git", "--git-dir="+e.remote, "ls-tree", "-r", "-z", commit).Output()
	if err != nil {
		e.t.Fatal(err)
	}
	tree := map[string]string{}
	for _, ent := range strings.Split(string(out), "\x00") {
		if tab := strings.IndexByte(ent, '\t'); tab > 0 {
			tree[ent[tab+1:]] = strings.Fields(ent[:tab])[2]
		}
	}
	return tree
}

func (e *env) writeBlob(data []byte) string {
	c := exec.Command("git", "--git-dir="+e.remote, "hash-object", "-w", "--stdin")
	c.Stdin = bytes.NewReader(data)
	out, err := c.Output()
	if err != nil {
		e.t.Fatal(err)
	}
	return strings.TrimSpace(string(out))
}

func (e *env) commitTree(entries map[string]string, parent string) string {
	idx := filepath.Join(e.root, "forge-index")
	defer os.Remove(idx)
	var info strings.Builder
	paths := make([]string, 0, len(entries))
	for p := range entries {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		fmt.Fprintf(&info, "100644 %s\t%s\n", entries[p], p)
	}
	run := func(stdin string, args ...string) string {
		c := exec.Command("git", append([]string{"--git-dir=" + e.remote}, args...)...)
		c.Env = append(os.Environ(), "GIT_INDEX_FILE="+idx, "GIT_AUTHOR_NAME=genc", "GIT_AUTHOR_EMAIL=genc@localhost",
			"GIT_COMMITTER_NAME=genc", "GIT_COMMITTER_EMAIL=genc@localhost")
		c.Stdin = strings.NewReader(stdin)
		out, err := c.CombinedOutput()
		if err != nil {
			e.t.Fatalf("git %v: %v\n%s", args, err, out)
		}
		return strings.TrimSpace(string(out))
	}
	run(info.String(), "update-index", "--add", "--index-info")
	tree := run("", "write-tree")
	args := []string{"commit-tree", tree, "-m", "genc update"}
	if parent != "" {
		args = append(args, "-p", parent)
	}
	return run("", args...)
}

// forgeCommit rewrites files of a storage commit.
func (e *env) forgeCommit(base string, edit func(path string, data []byte) []byte) string {
	entries := map[string]string{}
	for p, sha := range e.readTree(base) {
		data := e.blob(sha)
		if nd := edit(p, data); !bytes.Equal(nd, data) {
			sha = e.writeBlob(nd)
		}
		entries[p] = sha
	}
	return e.commitTree(entries, base)
}

func keyBox(t *testing.T, k crypt.Key, pubLine string) []byte {
	rcp, err := agessh.ParseRecipient(pubLine)
	if err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	w, _ := age.Encrypt(&out, rcp)
	w.Write(k[:])
	w.Close()
	return out.Bytes()
}

// forgeTakeover builds a complete, well-formed state with a new key that adds the
// attacker as a member and is validly signed by the attacker's own key.
func (e *env) forgeTakeover(attacker *user, base string) string {
	t := e.t
	m := e.readManifest(base)
	pemData, _ := os.ReadFile(attacker.keyPath())
	raw, err := ssh.ParseRawPrivateKey(pemData)
	if err != nil {
		t.Fatal(err)
	}
	signer, _ := ssh.NewSignerFromKey(raw)
	k, _ := crypt.NewKey()
	m.Members = append(m.Members, member{FP: fingerprint(signer.PublicKey()), Key: attacker.pubLine()})
	m.KeyID, m.Version, m.Signer = k.IDHex(), m.Version+1, fingerprint(signer.PublicKey())
	mraw, _ := json.MarshalIndent(m, "", "  ")
	sig, err := sshsig.Sign(signer, "genc-manifest@v1", mraw)
	if err != nil {
		t.Fatal(err)
	}
	entries := map[string]string{
		"keys/manifest.json": e.writeBlob(mraw),
		"keys/manifest.sig":  e.writeBlob(sig),
	}
	for _, mem := range m.Members {
		entries["keys/"+mem.FP+".key"] = e.writeBlob(keyBox(t, k, mem.Key))
	}
	idx, _ := json.Marshal(map[string]any{"format": 1, "repo_id": m.RepoID, "seq": 1 << 40,
		"refs": map[string]string{}, "names": map[string]string{}})
	ct, _ := crypt.EncryptBytes(idx, k, "index", "index|"+m.RepoID)
	entries["index.enc"] = e.writeBlob(ct)
	return e.commitTree(entries, base)
}

func genEd25519() (ed25519.PublicKey, ed25519.PrivateKey, error) {
	return ed25519.GenerateKey(rand.Reader)
}

func pemBytes(b *pem.Block) []byte { return pem.EncodeToMemory(b) }
